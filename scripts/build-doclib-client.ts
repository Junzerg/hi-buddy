/** Emit the document-library browser bundle from its UI source and stylesheet. */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { build } from 'esbuild'

const directory = resolve(import.meta.dirname, '../haiercash/builtin-plugins/hi-buddy-doclib-kit')
const result = await build({
  absWorkingDir: resolve(import.meta.dirname, '..'),
  entryPoints: [resolve(directory, 'src/client/index.js')],
  bundle: true,
  write: false,
  format: 'iife',
  target: 'es2022',
  loader: { '.css': 'text' },
  banner: { js: '// Generated by pnpm run build:doclib-client. Edit src/client/ instead.' },
})
const output = result.outputFiles[0]?.text
if (output === undefined) throw new Error('doclib: esbuild produced no client bundle')
const target = resolve(directory, 'client.js')
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('doclib: client.js is stale; run pnpm run build:doclib-client')
} else {
  await writeFile(target, output)
}
